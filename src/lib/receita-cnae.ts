const normalize = (v: string) => v.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
const INDEX = RECEITA_CNAES.map(c => ({ ...c, haystack: `${normalize(c.description)} ${c.code}` }));
const byCode = new Map(RECEITA_CNAES.map(c => [c.code, c.description]));
export function receitaCnaeDescription(code: string | null | undefined) { return code ? byCode.get(code) ?? "" : ""; }
/** Sugestões de CNAEs: todas as palavras digitadas precisam aparecer na descrição ou código. */
export function searchReceitaCnaes(term: string, limit = 12) {
  const words = normalize(term.trim()).split(/\s+/).filter(Boolean);
  if (!words.length || term.trim().length < 2) return [];
  const scored: Array<{ code: string; description: string; score: number }> = [];
  for (const c of INDEX) {
    if (!words.every(w => c.haystack.includes(w))) continue;
    const starts = words.some(w => normalize(c.description).split(/\s+/).some(d => d.startsWith(w)));
    scored.push({ code: c.code, description: c.description, score: starts ? 0 : 1 });
  }
  scored.sort((a, b) => a.score - b.score || a.description.localeCompare(b.description, "pt-BR"));
  return scored.slice(0, limit).map(({ code, description }) => ({ code, description }));
}
