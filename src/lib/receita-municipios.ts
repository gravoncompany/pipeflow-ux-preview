const normalize = (v: string) => v.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
const byCode = new Map(RECEITA_MUNICIPIOS.map(m => [m.code, m.name]));
export function receitaMunicipioName(code: string | null | undefined) { return code ? byCode.get(code) ?? "" : ""; }
/** Sugestões de municípios de SC pelo nome digitado (sem acentos, qualquer parte do nome). */
export function searchReceitaMunicipios(term: string, limit = 8) {
  const t = normalize(term.trim());
  if (t.length < 2) return [];
  return RECEITA_MUNICIPIOS.filter(m => normalize(m.name).includes(t)).slice(0, limit);
}
